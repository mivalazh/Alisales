/** Translate a Persian product string; an explicit English override wins. */
export function translate(fa: string, en?: string): string {
  return en ?? EN_DICTIONARY[fa] ?? fa;
}

/** English relative posting age, matching `postingAgeLabel` thresholds. */
export function postingAgeEnglish(
  publishedAt: Date | number | string,
  now: Date | number | string = Date.now(),
): string {
  const then = new Date(publishedAt).getTime();
  const current = new Date(now).getTime();
  const days = Math.max(0, Math.floor((current - then) / 86_400_000));
  if (days <= 0) return 'Today';
  if (days === 1) return 'Yesterday';
  if (days <= 6) return `${days} days ago`;
  if (days <= 13) return '1 week ago';
  if (days <= 20) return '2 weeks ago';
  if (days <= 27) return '3 weeks ago';
  if (days <= 59) return '1 month ago';
  if (days <= 89) return '2 months ago';
  const months = Math.floor(days / 30);
  return months >= 12 ? 'Over a year ago' : `${months} months ago`;
}
